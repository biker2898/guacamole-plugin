async function openSession(conn, attempt = 0) {
  show("viewer");
  setStatus(attempt ? "Connection lost. Reconnecting…" : "Connecting to " + conn.name + "…");
  const video = $("screen");
  const { w: width, h: height } = wantedSize();

  const pc = new RTCPeerConnection({ bundlePolicy: "max-bundle" });
  const dc = pc.createDataChannel("input", { ordered: true });
  pc.addTransceiver("video", { direction: "recvonly" });
  pc.addTransceiver("audio", { direction: "recvonly" });
  const ws = new WebSocket(`wss://${location.host}/api/session?id=${conn.id}`);
  const s = {
    conn, attempt, connected: false, lost: false, error: null, retry: false, pc, dc, ws, remote: { w: width, h: height }, timers: [], cleanup: [],
    keyChain: Promise.resolve(), clipIn: "", cursors: new Map(),
  };
  current = s;

  pc.ontrack = (e) => {
    if (e.track.kind === "audio") {
      const sound = $("sound");
      sound.srcObject = new MediaStream([e.track]);
      sound.play().catch(() => { /* needs a click first; the next one starts it */ });
      return;
    }
    video.srcObject = new MediaStream([e.track]);
    // Ask Chrome for the smallest jitter buffer.
    try { e.receiver.playoutDelayHint = 0; } catch (_) { /* unsupported */ }
    try { e.receiver.jitterBufferTarget = 0; } catch (_) { /* unsupported */ }
  };
  dc.onmessage = (ev) => onServerMessage(s, video, ev.data);
  pc.onconnectionstatechange = () => {
    if (pc.connectionState === "failed") sessionLost(s);
  };

  ws.onopen = async () => {
    await pc.setLocalDescription(await pc.createOffer());
    await waitForIce(pc, 1500);
    ws.send(JSON.stringify({ offer: pc.localDescription.sdp, width, height }));
  };
  ws.onmessage = async (ev) => {
    const msg = JSON.parse(ev.data);
    if (msg.answer) {
      s.remote = { w: msg.width, h: msg.height };
      await pc.setRemoteDescription({ type: "answer", sdp: msg.answer });
    } else if (msg.status === "connected") {
      setStatus("");
      s.connected = true;
      s.attempt = 0;
      video.focus();
      // The window may have changed while connecting.
      if (getRes() === "fit") resizeRemote(s);
    } else if (msg.error) {
      s.error = msg.error;
      s.retry = !!msg.retry;
      setStatus(msg.error);
    }
  };
  ws.onclose = () => sessionLost(s);

  attachInput(s, video);
  s.timers.push(setInterval(() => updateStats(s), 1000));
}

function waitForIce(pc, ms) {
  if (pc.iceGatheringState === "complete") return Promise.resolve();
  return new Promise((resolve) => {
    const t = setTimeout(resolve, ms);
    pc.addEventListener("icegatheringstatechange", () => {
      if (pc.iceGatheringState === "complete") { clearTimeout(t); resolve(); }
    });
  });
}

function closeSession() {
  const s = current;
  current = null;
  if (!s) return;
  for (const t of s.timers) clearInterval(t);
  for (const f of s.cleanup) f();
  try { s.ws.close(); } catch (_) { /* already closed */ }
  try { s.pc.close(); } catch (_) { /* already closed */ }
  $("screen").srcObject = null;
  $("screen").style.cursor = "";
  $("sound").srcObject = null;
}

$("leave").addEventListener("click", () => {
  if (document.fullscreenElement) document.exitFullscreen();
  closeSession();
  api("/api/me").then((r) => (r.ok ? home(r.data) : show("login")));
});

function send(s, msg) {
  if (s.dc.readyState === "open") s.dc.send(JSON.stringify(msg));
}

// Maps a pointer event to remote desktop pixels, accounting for letterboxing.
function remotePos(s, video, e) {
  const r = video.getBoundingClientRect();
  const scale = Math.min(r.width / s.remote.w, r.height / s.remote.h);
  const offX = (r.width - s.remote.w * scale) / 2;
  const offY = (r.height - s.remote.h * scale) / 2;
  const x = Math.round((e.clientX - r.left - offX) / scale);
  const y = Math.round((e.clientY - r.top - offY) / scale);
  return {
    x: Math.max(0, Math.min(s.remote.w - 1, x)),
    y: Math.max(0, Math.min(s.remote.h - 1, y)),
  };
}

function attachInput(s, video) {
  let pendingMove = null;
  let raf = 0;
  const flushMove = () => {
    raf = 0;
    if (pendingMove) send(s, { t: "m", ...pendingMove });
    pendingMove = null;
  };
  const on = (target, type, fn, opts) => {
    target.addEventListener(type, fn, opts);
    s.cleanup.push(() => target.removeEventListener(type, fn, opts));
  };

  on(video, "pointermove", (e) => {
    pendingMove = remotePos(s, video, e);
    if (!raf) raf = requestAnimationFrame(flushMove);
  });
  on(video, "pointerdown", (e) => {
    e.preventDefault();
    video.focus();
    const sound = $("sound");
    if (sound.srcObject && sound.paused) sound.play().catch(() => {});
    video.setPointerCapture(e.pointerId);
    pendingMove = null;
    send(s, { t: "b", b: e.button, d: true, ...remotePos(s, video, e) });
  });
  on(video, "pointerup", (e) => {
    e.preventDefault();
    send(s, { t: "b", b: e.button, d: false, ...remotePos(s, video, e) });
  });
  on(video, "contextmenu", (e) => e.preventDefault());
  // Wheel: one Windows notch (120) per mouse-wheel click. Touchpads and
  // smooth-scrolling mice fire many small events per click; each used to be
  // sent as a full notch, so Excel scrolled far past where the user stopped
  // and kept scrolling after. Deltas now add up until they make a notch.
  const wheel = { x: 0, y: 0 };
  const NOTCH = { 0: 100, 1: 3, 2: 1 }; // pixels, lines or pages per notch (deltaMode)
  on(video, "wheel", (e) => {
    e.preventDefault();
    const per = NOTCH[e.deltaMode] || 100;
    // A change of direction starts over.
    const add = (acc, d) => (acc * d < 0 ? 0 : acc) + d / per;
    wheel.y = add(wheel.y, e.deltaY);
    wheel.x = add(wheel.x, e.deltaX);
    // Never more than a few notches per event, whatever the browser reports.
    const take = (v) => Math.max(-4, Math.min(4, Math.trunc(v)));
    const ny = take(wheel.y), nx = take(wheel.x);
    wheel.y -= Math.trunc(wheel.y) === ny ? ny : Math.trunc(wheel.y);
    wheel.x -= Math.trunc(wheel.x) === nx ? nx : Math.trunc(wheel.x);
    for (let i = 0; i < Math.abs(ny); i++) send(s, { t: "w", v: ny > 0 ? -120 : 120 });
    for (let i = 0; i < Math.abs(nx); i++) send(s, { t: "w", v: nx > 0 ? 120 : -120, h: true });
  }, { passive: false });

  // Keys go out in order through one promise chain, so Ctrl+V can wait for
  // the local clipboard to reach Windows before the V itself is sent.
  const key = (down) => (e) => {
    // Typing in the page's own controls (paste box, size list) stays local.
    if (e.target.closest && e.target.closest("dialog, input, textarea, select")) return;
    const c = SCANCODES[e.code];
    if (c === undefined) return;
    // Held modifiers: send the press once. Windows needs no repeats for them,
    // and a stream of Shift presses can trigger Sticky Keys.
    if (e.repeat && MODIFIERS.has(e.code)) return void e.preventDefault();
    const isPaste = down && e.code === "KeyV" && (e.ctrlKey || e.metaKey) && !e.repeat;
    // Ctrl+V keeps its default, so the browser fires a paste event carrying
    // the clipboard (works in Firefox, which refuses clipboard.readText).
    if (!isPaste) e.preventDefault();
    const clip = isPaste ? clipboardForPaste(s) : null;
    s.keyChain = s.keyChain
      .then(() => clip)
      .then(() => send(s, { t: "k", c, d: down }));
  };
  on(window, "keydown", key(true));
  on(window, "keyup", key(false));
  on(window, "blur", () => send(s, { t: "r" }));
  on(window, "focus", () => { pushClipboard(s); retryClipboardWrite(); });
}

// ---------- clipboard (text) ----------

// Text last seen on either side, so a copy is not echoed back.
let lastClip = null;
let pendingClipWrite = null;
const CLIP_CHUNK = 16 * 1024;

// Reads the browser clipboard; null if the browser refuses or takes longer
// than `ms` (e.g. while a permission prompt or Firefox's Paste bubble is open).
async function readClipboard(ms) {
  if (!navigator.clipboard || !navigator.clipboard.readText) return null;
  try {
    const text = await Promise.race([
      navigator.clipboard.readText(),
      new Promise((resolve) => setTimeout(() => resolve(null), ms)),
    ]);
    return typeof text === "string" ? text : null;
  } catch (_) {
    return null; // permission denied or page not focused
  }
}

// Sends the browser clipboard to Windows if it changed. Resolves once sent.
async function pushClipboard(s) {
  await sendClipboard(s, await readClipboard(1500));
}

// The paste event for the Ctrl+V being handled, if any.
let pasteWaiter = null;
window.addEventListener("paste", (e) => {
  if (!current || (e.target.closest && e.target.closest("dialog"))) return;
  e.preventDefault();
  const text = e.clipboardData ? e.clipboardData.getData("text/plain") : "";
  if (pasteWaiter) pasteWaiter(text);
  else sendClipboard(current, text);
});

// On Ctrl+V: takes the clipboard from the paste event that follows, or
// asks for it directly if the browser fires none. Resolves once sent.
function clipboardForPaste(s) {
  return new Promise((resolve) => {
    const timer = setTimeout(() => {
      pasteWaiter = null;
      resolve(pushClipboard(s));
    }, 300);
    pasteWaiter = (text) => {
      clearTimeout(timer);
      pasteWaiter = null;
      resolve(sendClipboard(s, text));
    };
  });
}

// Offers `text` to Windows as its clipboard, unless it already has it.
async function sendClipboard(s, text) {
  if (typeof text !== "string" || !text || text === lastClip) return;
  lastClip = text;
  for (let i = 0; i < text.length || i === 0; i += CLIP_CHUNK) {
    send(s, { t: "c", d: text.slice(i, i + CLIP_CHUNK), more: i + CLIP_CHUNK < text.length });
  }
  // Let Windows take the new clipboard before the paste key arrives.
  await new Promise((resolve) => setTimeout(resolve, 60));
}

// Paste button (touch screens): send the clipboard and press Ctrl+V in Windows.
// Browsers that will not hand the clipboard over get a box to paste into.
function pasteInto(s, text) {
  s.keyChain = s.keyChain
    .then(() => sendClipboard(s, text))
    .then(() => {
      for (const [c, d] of [[0x1d, true], [0x2f, true], [0x2f, false], [0x1d, false]]) send(s, { t: "k", c, d });
    });
}

