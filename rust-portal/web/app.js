// Shows a message over the screen; with `retry`, a Reconnect button under it.
function setStatus(text, retry) {
  const el = $("status");
  el.replaceChildren(text);
  if (retry) {
    const b = document.createElement("button");
    b.textContent = "Reconnect";
    b.className = "btn";
    b.style.cssText = "display:block;margin:12px auto 0";
    b.addEventListener("click", retry);
    el.append(b);
  }
  el.classList.toggle("hidden", !text);
}

// Waits before each automatic reconnect after the connection drops.
const RETRY_DELAYS = [1000, 2000, 5000, 10000, 20000, 30000];

// The session dropped. Windows keeps the desktop, so reconnect by itself,
// unless it never worked or Windows / an administrator ended it.
function sessionLost(s) {
  if (current !== s || s.lost) return;
  s.lost = true;
  const manual = () => { if (current === s) { closeSession(); openSession(s.conn); } };
  const canRetry = (s.connected || s.attempt > 0) && (!s.error || s.retry);
  if (!canRetry || s.attempt >= RETRY_DELAYS.length) {
    return setStatus(s.error || "Disconnected.", manual);
  }
  setStatus("Connection lost. Reconnecting…", manual);
  setTimeout(() => {
    if (current !== s) return;
    closeSession();
    openSession(s.conn, s.attempt + 1);
  }, RETRY_DELAYS[s.attempt]);
}

// ---------- screen size and full screen ----------

const RES_OPTIONS = [
  ["fit", "Fit to window"],
  ["1280x720", "1280 × 720"],
  ["1366x768", "1366 × 768"],
  ["1600x900", "1600 × 900"],
  ["1920x1080", "1920 × 1080"],
];
// Same limits as the server.
const MIN_W = 640, MIN_H = 480, MAX_W = 1920, MAX_H = 1080;
// Computers that cannot change size live; for them a size change reconnects.
const noLiveResize = new Set();

function getRes() {
  let v = null;
  try { v = localStorage.getItem("res"); } catch (_) { /* storage blocked */ }
  return RES_OPTIONS.some((o) => o[0] === v) ? v : "fit";
}

function setRes(v) {
  try { localStorage.setItem("res", v); } catch (_) { /* storage blocked */ }
  for (const id of ["res", "hud-res"]) $(id).value = v;
}

// The desktop size to ask for: the chosen one, or the window (sharp on HiDPI, up to 1.5x).
function wantedSize() {
  const v = getRes();
  let w, h;
  if (v === "fit") {
    const dpr = Math.min(window.devicePixelRatio || 1, 1.5);
    w = Math.round(window.innerWidth * dpr);
    h = Math.round(window.innerHeight * dpr);
    // Larger windows: scale down to fit 1920 x 1080, keeping the shape.
    const k = Math.min(1, MAX_W / w, MAX_H / h);
    w = Math.round(w * k);
    h = Math.round(h * k);
  } else {
    [w, h] = v.split("x").map(Number);
  }
  const even = (n, lo, hi) => Math.min(hi, Math.max(lo, n)) & ~1;
  return { w: even(w, MIN_W, MAX_W), h: even(h, MIN_H, MAX_H) };
}

for (const id of ["res", "hud-res"]) {
  for (const [v, label] of RES_OPTIONS) $(id).append(new Option(label, v));
  $(id).value = getRes();
}
$("res").addEventListener("change", (e) => setRes(e.target.value));
$("hud-res").addEventListener("change", (e) => {
  setRes(e.target.value);
  $("screen").focus();
  if (current) resizeRemote(current);
});

// Asks Windows for the wanted size, live where possible, otherwise by reconnecting.
function resizeRemote(s) {
  if (!s.connected) return;
  const { w, h } = wantedSize();
  if (w === s.remote.w && h === s.remote.h) return;
  if (noLiveResize.has(s.conn.id)) return reconnect(s);
  send(s, { t: "size", w, h });
}

function reconnect(s) {
  if (current !== s) return;
  closeSession();
  openSession(s.conn);
}

let resizeTimer = 0;
window.addEventListener("resize", () => {
  clearTimeout(resizeTimer);
  // Wait until the window stops changing: each change makes Windows redo the desktop.
  resizeTimer = setTimeout(() => {
    if (current && getRes() === "fit") resizeRemote(current);
  }, 700);
});

